# ───────────── אימות ─────────────
def run(code):
    buf = io.StringIO()
    err = None
    home = os.getcwd()
    with tempfile.TemporaryDirectory() as tmp:   # each question gets an empty folder
        os.chdir(tmp)
        try:
            with contextlib.redirect_stdout(buf):
                exec(compile(code, "<q>", "exec"), {"__name__": "__main__"})
        except BaseException as e:
            err = type(e).__name__
        finally:
            os.chdir(home)
    out = buf.getvalue().rstrip()
    out = "\n".join(l.rstrip() for l in out.split("\n")) if out else ""
    out = re.sub(r"0x[0-9a-fA-F]+", "0x…", out)
    if err:
        out = (out + "\n" if out else "") + "ERR:" + err
    return out

bad = 0
for i, item in enumerate(Q):
    actual = run(item["code"])
    exp = item["opts"][item["ans"]]
    assert len(item["opts"]) == 4 and len(item["why"]) == 4, i
    assert len(set(item["opts"])) == 4, (i, "duplicate options")
    if actual != exp:
        bad += 1
        print(f"#{i} MISMATCH\n  code: {item['code'][:60]!r}\n  expected: {exp!r}\n  actual:   {actual!r}")
    item["out"] = actual
print(f"{len(Q)} questions, {bad} mismatches")
json.dump(Q, open("questions.json", "w"), ensure_ascii=False)
